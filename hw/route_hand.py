# 사용: python hw/route_hand.py [출력.json]  → hw/autoroute45.py 의 두 번째 인자로 넘긴다
import json, math, sys
from kipy import KiCad

PADS = {}
for f in KiCad().get_board().get_footprints():
    for p in f.definition.pads:
        if p.number:
            PADS.setdefault(f.reference_field.text.value, []).append(
                {"n": p.number, "net": p.net.name, "x": round(p.position.x / 1e6, 3), "y": round(p.position.y / 1e6, 3)})
OUT = sys.argv[1] if len(sys.argv) > 1 else "hand.json"
routes, vias, hand = [], [], set()


def pd(r, n, k=0):
    return [p for p in PADS[r] if p["n"] == n][k]


def c(r, n, k=0):
    p = pd(r, n, k)
    return (p["x"], p["y"])


def net(key):
    return key if isinstance(key, str) else pd(*key)["net"]


def T(key, pts, w, L="F", pads=(), kelvin=False):
    pts = [(round(x, 4), round(y, 4)) for x, y in pts]
    for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
        dx, dy = abs(x2 - x1), abs(y2 - y1)
        assert dx < 1e-6 or dy < 1e-6 or abs(dx - dy) < 1e-3, ("45도 아님", key, (x1, y1), (x2, y2))
    routes.append({"net": net(key), "layer": "F.Cu" if L == "F" else "B.Cu", "width": w, "pts": [list(p) for p in pts]})
    if kelvin:                          # autoroute45.py가 GND 비아를 이 선에 붙이지 않게
        routes[-1]["kelvin"] = True
    if not isinstance(key, str):
        hand.add(tuple(key))
    for p in pads:
        hand.add(tuple(p))


def V(key, x, y, d=0.6):
    vias.append({"net": net(key), "x": round(x, 4), "y": round(y, 4), "d": d, "drill": 0.3 if d >= 0.6 else 0.25})


def d45(p, q, first):
    """p→q: 첫 구간을 세로(v)나 가로(h)로 가고 45°로 q에 닿는다."""
    dx, dy = q[0] - p[0], q[1] - p[1]
    if first == "v":
        return [p, (p[0], q[1] - math.copysign(abs(dx), dy)), q]
    return [p, (q[0] - math.copysign(abs(dy), dx), p[1]), q]


